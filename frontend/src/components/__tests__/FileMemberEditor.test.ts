import { mount, flushPromises } from '@vue/test-utils'
import { beforeEach, expect, it, vi } from 'vitest'
import FileMemberEditor from '../FileMemberEditor.vue'

const api = vi.hoisted(() => ({ fileMemberList: vi.fn(), fileMemberReplace: vi.fn(), fileMemberCandidates: vi.fn() }))
vi.mock('../../services/core', () => ({ core: api }))
beforeEach(() => {
  vi.clearAllMocks()
  api.fileMemberList.mockResolvedValue([{ memberType: 'user', memberId: '9007199254740993', role: 'manage', memberName: '自己' }])
  api.fileMemberReplace.mockResolvedValue(undefined)
  api.fileMemberCandidates.mockResolvedValue([])
})
it('自己的成员行只读且保存空组时剔除自己', async () => {
  const wrapper = mount(FileMemberEditor, { props: { fileId: '100', fileName: '合同', operatorId: '9007199254740993' } })
  await flushPromises()
  expect(wrapper.find('select[aria-label="自己的角色"]').attributes('disabled')).toBeDefined()
  expect(wrapper.find('[data-testid="remove-member"]').attributes('disabled')).toBeDefined()
  await wrapper.find('[data-testid="save-members"]').trigger('click')
  await flushPromises()
  expect(api.fileMemberReplace).toHaveBeenCalledWith('100', [])
})
it('切换文件后迟到的成员请求不能覆盖新文件', async () => {
  let resolveOld!: (rows: unknown[]) => void
  api.fileMemberList.mockImplementationOnce(() => new Promise(resolve => { resolveOld = resolve }))
  const wrapper = mount(FileMemberEditor, { props: { fileId: 'old', fileName: '旧文件', operatorId: '7' } })
  await wrapper.setProps({ fileId: 'new', fileName: '新文件' })
  await flushPromises()
  resolveOld([{ memberType: 'user', memberId: '8', role: 'read', memberName: '旧文件成员' }])
  await flushPromises()
  expect(wrapper.text()).not.toContain('旧文件成员')
})
it('没有匹配成员时给出可恢复的搜索提示', async () => {
  const wrapper = mount(FileMemberEditor, { props: { fileId: '100', fileName: '合同', operatorId: '7' } })
  await flushPromises()
  await wrapper.get('input[aria-label="搜索成员或部门"]').setValue('不存在的成员')
  await wrapper.get('.file-member-search').trigger('submit')
  await flushPromises()
  expect(wrapper.text()).toContain('没有匹配的有效成员或部门，请换一个关键词')
})

it('空组保存失败后能重试，忙时防止重复提交', async () => {
  api.fileMemberList.mockResolvedValue([])
  api.fileMemberReplace.mockRejectedValueOnce(new Error('网络失败')).mockResolvedValueOnce(undefined)
  const wrapper = mount(FileMemberEditor, { props: { fileId: '100', fileName: '合同', operatorId: '7' } })
  await flushPromises()
  await wrapper.find('[data-testid="save-members"]').trigger('click')
  await flushPromises()
  expect(wrapper.text()).toContain('网络失败')
  expect(wrapper.find('[data-testid="save-members"]').attributes('disabled')).toBeUndefined()
  await wrapper.find('[data-testid="save-members"]').trigger('click')
  await flushPromises()
  expect(api.fileMemberReplace).toHaveBeenCalledTimes(2)
})

const deferred = <T,>() => { let resolve!: (value: T) => void; let reject!: (reason: unknown) => void; const promise = new Promise<T>((a, b) => { resolve = a; reject = b }); return { promise, resolve, reject } }
it('成员读取失败不冒充空授权，也不开放保存和搜索', async () => {
  api.fileMemberList.mockRejectedValueOnce(new Error('读取拒绝'))
  const w = mount(FileMemberEditor, { props: { fileId: '100', fileName: '合同', operatorId: '7' } })
  await flushPromises()
  expect(w.text()).toContain('成员读取失败')
  expect(w.text()).not.toContain('当前没有显式成员行')
  expect(w.find('[data-testid="save-members"]').exists()).toBe(false)
  expect(w.find('.file-member-search').exists()).toBe(false)
  await w.get('.text-button').trigger('click')
  await flushPromises()
  expect(w.find('[data-testid="save-members"]').exists()).toBe(true)
})
it('修改关键词立即淘汰在途候选结果', async () => {
  const request = deferred<unknown[]>()
  api.fileMemberCandidates.mockReturnValueOnce(request.promise)
  const w = mount(FileMemberEditor, { props: { fileId: '100', fileName: '合同', operatorId: '7' } })
  await flushPromises()
  await w.get('input').setValue('旧姓名')
  await w.get('form').trigger('submit')
  await w.get('input').setValue('新姓名')
  request.resolve([{ memberType: 'user', memberId: '8', memberName: '旧候选', grantable: true }])
  await flushPromises()
  expect(w.text()).not.toContain('旧候选')
  expect(w.text()).not.toContain('没有匹配的有效成员')
})
it('在途保存仅提交一次，切换文件后完成不冒报新文件成功', async () => {
  const request = deferred<void>()
  api.fileMemberReplace.mockReturnValueOnce(request.promise)
  const w = mount(FileMemberEditor, { props: { fileId: '100', fileName: '合同', operatorId: '7' } })
  await flushPromises()
  await w.get('[data-testid="save-members"]').trigger('click')
  await w.get('[data-testid="save-members"]').trigger('click')
  expect(api.fileMemberReplace).toHaveBeenCalledTimes(1)
  await w.setProps({ fileId: '200', fileName: '新文件' })
  await flushPromises()
  request.resolve()
  await flushPromises()
  expect(w.emitted('saved')).toBeUndefined()
  expect(w.text()).not.toContain('成员角色已保存')
  expect(w.get('[data-testid="save-members"]').attributes('disabled')).toBeUndefined()
})
it('移除需确认，确认后仍保留为待保存草稿', async () => {
  api.fileMemberList.mockResolvedValue([{ memberType: 'user', memberId: '8', memberName: '小李', role: 'read' }])
  const w = mount(FileMemberEditor, { props: { fileId: '100', fileName: '合同', operatorId: '7' } })
  await flushPromises()
  await w.get('[data-testid="remove-member"]').trigger('click')
  expect(w.findAll('.role-actions')).toHaveLength(1)
  expect(api.fileMemberReplace).not.toHaveBeenCalled()
  await w.get('[data-testid="confirm-remove-member"]').trigger('click')
  expect(w.findAll('.role-actions')).toHaveLength(0)
  expect(w.text()).toContain('有未保存的成员变更')
  expect(api.fileMemberReplace).not.toHaveBeenCalled()
  await w.get('[data-testid="save-members"]').trigger('click')
  await flushPromises()
  expect(api.fileMemberReplace).toHaveBeenCalledWith('100', [])
})
it('修改草稿清除旧成功提示，失败后保留角色选择', async () => {
  api.fileMemberList.mockResolvedValue([{ memberType: 'user', memberId: '8', role: 'read' }])
  const w = mount(FileMemberEditor, { props: { fileId: '100', fileName: '合同', operatorId: '7' } })
  await flushPromises()
  await w.get('[data-testid="save-members"]').trigger('click'); await flushPromises()
  expect(w.text()).toContain('成员角色已保存')
  await w.get('select').setValue('edit')
  expect(w.text()).not.toContain('成员角色已保存')
  api.fileMemberReplace.mockRejectedValueOnce(new Error('不可授权'))
  await w.get('[data-testid="save-members"]').trigger('click'); await flushPromises()
  expect((w.get('select').element as HTMLSelectElement).value).toBe('edit')
  expect(w.text()).toContain('保存失败：不可授权')
  expect(w.text()).not.toContain('重试读取')
})
